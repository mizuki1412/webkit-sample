#!/usr/bin/env python3
"""
build.py - compile out/tokens.json into consumable frontend artifacts.

    tokens.json  ->  theme.css            (CSS custom properties, any stack)
                 ->  tailwind.v4.css      (Tailwind v4 @theme block)
                 ->  tokens.js            (ESM token map: import in Vue/JS)
                 ->  tokens.flat.json     (var -> value map, used by design_lint)

The target project (webkit-sample) uses Tailwind CSS 4 + Vue 3, so the
primary Tailwind output is the v4 `@theme` form. A legacy v3 preset is
still emitted for projects that have not migrated.

Run: python tools/build.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "out"


def walk(node: dict, path: list[str]):
    """Yield (path, type, value) for every DTCG leaf."""
    group_type = node.get("$type")
    for key, child in node.items():
        if key.startswith("$"):
            continue
        if isinstance(child, dict) and "$value" in child:
            yield path + [key], child.get("$type", group_type), child["$value"]
        elif isinstance(child, dict):
            yield from walk(child, path + [key])


def var_name(path: list[str]) -> str:
    head = path[0]
    rest = path[1:]
    if head == "color":
        return "--color-" + "-".join(rest)
    if head == "space":
        return "--space-" + "-".join(rest)
    if head == "radius":
        return "--radius-" + "-".join(rest)
    if head == "font":
        if rest[0] == "family":
            return "--font-family"
        prefixes = {"size": "--font-size-", "weight": "--font-weight-",
                    "leading": "--leading-", "tracking": "--tracking-"}
        return prefixes[rest[0]] + "-".join(rest[1:])
    if head == "motion":
        return ("--duration-" if rest[0] == "duration" else "--ease-") + "-".join(rest[1:])
    if head == "chart":
        return "--chart-" + "-".join(rest)
    return "--" + "-".join(path)


def css_value(value, type_: str) -> str:
    if type_ == "fontFamily":
        return ", ".join(f'"{v}"' if " " in v else v for v in value)
    if type_ == "cubicBezier":
        return "cubic-bezier(" + ", ".join(str(v) for v in value) + ")"
    return str(value)


def tw_value(value, type_: str) -> str:
    """Tailwind v4 kebab namespaces, e.g. --color-accent, --spacing-4."""
    if type_ == "fontFamily":
        return ", ".join(f'"{v}"' if " " in v else v for v in value)
    if type_ == "cubicBezier":
        return "cubic-bezier(" + ", ".join(str(v) for v in value) + ")"
    return str(value)


def main() -> None:
    tokens = json.loads((OUT / "tokens.json").read_text(encoding="utf-8"))
    flat: list[tuple[str, str, str, str]] = []  # path, type, value, cssvar

    for path, type_, value in walk(tokens, []):
        flat.append((".".join(path), type_, value, var_name(path)))

    by_var = {var: (t, v) for p, t, v, var in flat}

    # ---------------- theme.css (raw :root variables, any stack)
    lines = ["/* generated by tools/build.py from out/tokens.json - do not edit */",
             ":root {"]
    for _, type_, value, var in flat:
        lines.append(f"  {var}: {css_value(value, type_)};")
    lines.append("}")
    (OUT / "theme.css").write_text("\n".join(lines) + "\n", encoding="utf-8")

    # ---------------- tailwind.v4.css (@theme block)
    v4 = ["/* generated by tools/build.py from out/tokens.json - do not edit */",
          "/* import this from your tailwind entry, AFTER @import \"tailwindcss/theme.css\" */",
          "@theme {", "  /* color */"]
    for var, (type_, value) in sorted(by_var.items()):
        if type_ == "color":
            v4.append(f"  {var}: {tw_value(value, type_)};")
    v4.append("")
    v4.append("  /* spacing (named scale on top of Tailwind default) */")
    for var, (type_, value) in sorted(by_var.items()):
        if var.startswith("--space-"):
            v4.append(f"  --spacing-{var[len('--space-'):]}: {value};")
    v4.append("")
    v4.append("  /* radius */")
    for var, (type_, value) in sorted(by_var.items()):
        if var.startswith("--radius-"):
            v4.append(f"  {var}: {value};")
    v4.append("")
    v4.append("  /* font */")
    fam = next(v for v, (t, vv) in by_var.items() if t == "fontFamily")
    v4.append(f"  {fam}: {by_var[fam][1]};")
    for var, (type_, value) in sorted(by_var.items()):
        if type_ in ("dimension",) and var.startswith(
                ("--font-size-", "--font-weight-", "--leading-", "--tracking-")):
            v4.append(f"  {var}: {value};")
    v4.append("")
    v4.append("  /* motion */")
    for var, (type_, value) in sorted(by_var.items()):
        if var.startswith(("--duration-", "--ease-")):
            v4.append(f"  {var}: {value};")
    v4.append("")
    v4.append("  /* chart */")
    for var, (type_, value) in sorted(by_var.items()):
        if var.startswith("--chart-"):
            v4.append(f"  {var}: {value};")
    v4.append("}")
    (OUT / "tailwind.v4.css").write_text("\n".join(v4) + "\n", encoding="utf-8")

    # ---------------- legacy tailwind v3 preset (kept for non-v4 projects)
    def group(prefix: str, transform=lambda v: f"var({v})") -> dict:
        return {var[len(prefix):]: transform(var) for _, _, _, var in flat
                if var.startswith(prefix) and var != prefix}

    colors = group("--color-")
    spacing = group("--space-")
    radii = group("--radius-")
    font_sizes = group("--font-size-")
    font_weights = group("--font-weight-")
    line_heights = group("--leading-")
    tracking = group("--tracking-")
    preset = f"""/* generated by tools/build.py from out/tokens.json - do not edit */
/** @type {{import('tailwindcss').Config}} */
module.exports = {{
  theme: {{
    extend: {{
      colors: {json.dumps(colors, indent=8)},
      spacing: {json.dumps(spacing, indent=8)},
      borderRadius: {json.dumps(radii, indent=8)},
      fontFamily: {{ sans: "var(--font-family)" }},
      fontSize: {json.dumps(font_sizes, indent=8)},
      fontWeight: {json.dumps(font_weights, indent=8)},
      lineHeight: {json.dumps(line_heights, indent=8)},
      letterSpacing: {json.dumps(tracking, indent=8)}
    }}
  }}
}};
"""
    (OUT / "tailwind.preset.js").write_text(preset, encoding="utf-8")

    # ---------------- tokens.js (ESM map for Vue/JS)
    esm = ["// generated by tools/build.py from out/tokens.json - do not edit",
           "// import { tokens, cssVar } from './design/out/tokens.js'",
           "export const tokens = {", "  color: {"]
    for var, (type_, value) in sorted(by_var.items()):
        if type_ == "color":
            esm.append(f"    '{var[len('--color-'):]}': '{value}',")
    esm += ["  },", "  space: {"]
    for var, (type_, value) in sorted(by_var.items()):
        if var.startswith("--space-"):
            esm.append(f"    '{var[len('--space-'):]}': '{value}',")
    esm += ["  },", "  radius: {"]
    for var, (type_, value) in sorted(by_var.items()):
        if var.startswith("--radius-"):
            esm.append(f"    '{var[len('--radius-'):]}': '{value}',")
    esm += ["  },", "  font: {"]
    for var, (type_, value) in sorted(by_var.items()):
        if type_ in ("dimension", "fontFamily", "fontWeight", "number") and var.startswith(
                ("--font-",)):
            esm.append(f"    '{var[2:]}': '{value}',")
    esm += ["  },", "  layout: {"]
    for var, (type_, value) in sorted(by_var.items()):
        if var.startswith("--layout-"):
            esm.append(f"    '{var[len('--layout-'):]}': '{value}',")
    esm += ["  },", "  chart: {"]
    for var, (type_, value) in sorted(by_var.items()):
        if var.startswith("--chart-"):
            esm.append(f"    '{var[len('--chart-'):]}': '{value}',")
    esm += ["  },", "}", ""]
    esm.append("export const cssVar = (name) => `var(--${name})`;")
    esm.append("")
    (OUT / "tokens.js").write_text("\n".join(esm), encoding="utf-8")

    # ---------------- tokens.flat.json (lint whitelist)
    flat_map = {var: {"path": p, "type": t, "value": v} for p, t, v, var in flat}
    (OUT / "tokens.flat.json").write_text(
        json.dumps(flat_map, indent=2, ensure_ascii=False), encoding="utf-8")

    print(f"tokens   {len(flat)} leaves")
    for f in ("theme.css", "tailwind.v4.css", "tailwind.preset.js",
              "tokens.js", "tokens.flat.json"):
        print(f"written  {OUT / f}")


if __name__ == "__main__":
    main()
